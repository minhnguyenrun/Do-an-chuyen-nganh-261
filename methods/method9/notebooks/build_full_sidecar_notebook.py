            "            nn.Conv2d(in_channels, 64, kernel_size=3, padding=1, bias=False),\n",
            "            nn.BatchNorm2d(64),\n",
            "            nn.ReLU(inplace=True),\n",
            "            nn.Conv2d(64, 256, kernel_size=3, padding=1, bias=False),\n",
            "            nn.BatchNorm2d(256),\n",
            "            nn.ReLU(inplace=True),\n",
            "        )\n",
            "        # Stage 1: Downsample 2x -> 40x40, 512 channels\n",
            "        self.stage1 = nn.Sequential(\n",
            "            nn.MaxPool2d(kernel_size=2, stride=2),\n",
            "            nn.Conv2d(256, 512, kernel_size=3, padding=1, bias=False),\n",
            "            nn.BatchNorm2d(512),\n",
            "            nn.ReLU(inplace=True),\n",
            "        )\n",
            "        # Stage 2: Downsample 2x -> 20x20, 512 channels\n",
            "        self.stage2 = nn.Sequential(\n",
            "            nn.MaxPool2d(kernel_size=2, stride=2),\n",
            "            nn.Conv2d(512, 512, kernel_size=3, padding=1, bias=False),\n",
            "            nn.BatchNorm2d(512),\n",
            "            nn.ReLU(inplace=True),\n",
            "        )\n",
            "\n",
            "    def forward(self, x: torch.Tensor) -> list[torch.Tensor]:\n",
            "        s0 = self.stage0(x)     # [B, 256, 80, 80]\n",
            "        s1 = self.stage1(s0)    # [B, 512, 40, 40]\n",
            "        s2 = self.stage2(s1)    # [B, 512, 20, 20]\n",
            "        return [s0, s1, s2]\n",
            "\n",
            "\n",
